import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const source = await readFile(new URL('../insights-data.js', import.meta.url), 'utf8');
const { buildInsights, parseCough, chicagoParts, frequencyLabel } = await import(`data:text/javascript;base64,${Buffer.from(source).toString('base64')}`);
assert.equal(chicagoParts('2026-09-22T04:59:00Z').date, '2026-09-21');
assert.equal(chicagoParts('2026-09-22T05:00:00Z').date, '2026-09-22');
assert.equal(chicagoParts('2026-12-01T05:59:00Z').date, '2026-11-30');
assert.equal(parseCough('睡着时咳嗽20秒').low, null);
assert.equal(parseCough('咳嗽数下').low, null);
assert.deepEqual(parseCough('剧烈咳嗽15-20下'), {low:15,high:20,uncertain:false});
assert.equal(parseCough('没有咳嗽'), null);
assert.deepEqual(parseCough('至少二十多下咳嗽'), {low:21,high:null,uncertain:false});
assert.equal(frequencyLabel(null), 'Frequency unspecified');
assert.equal(frequencyLabel('每天2次'), 'BID');
assert.equal(frequencyLabel('每2天1次'), 'q48h');
const med = (id,day,dose=110) => ({id,occurred_at:`2026-09-${day}T15:00:00Z`,type:'inhaled',medicine:'Fluticasone',dose_amount:dose,dose_unit:'mcg',frequency:'每天2次'});
const records = [med('prior','20'), med('am','22'), {...med('pm','22'),occurred_at:'2026-09-23T03:00:00Z'},med('change','24',220),{id:'c',occurred_at:'2026-09-22T15:21:00Z',type:'behavior',note:'咳嗽7-8下'}, {id:'unknown',occurred_at:'2026-09-22T17:00:00Z',type:'behavior',note:'咳嗽20秒'}];
const d = buildInsights([...records,records[1]], '2026-09-21', '2026-09-24');
assert.equal(d.rows.length,5);
assert.equal(d.fluticasone.daily[0].total,220);
assert.equal(d.fluticasone.daily[0].count,2);
assert.equal(d.fluticasone.daily.length,2); // Missing logs are not zero-dose days.
assert.deepEqual(d.fluticasone.stages.map(s=>[s.start,s.end,s.label]),[['2026-09-21','2026-09-24','110 mcg BID'],['2026-09-24','2026-09-25','220 mcg BID']]);
assert.equal(d.coughDaily[0].count,2);
assert.equal(d.coughDaily[0].low,7);
assert.equal(d.coughDaily[0].unknown,1);
assert.equal(buildInsights(records,'2026-09-23','2026-09-23').rows.length,0);
assert.throws(()=>buildInsights(records,'2026-02-30','2026-03-02'));
assert.throws(()=>buildInsights(records,'2026-09-24','2026-09-21'));
console.log('Insights data checks passed.');
